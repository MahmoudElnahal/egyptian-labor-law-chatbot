from .arabic import normalize, stem

# التوكنز اللي بتوصل هنا متجرّدة، فلازم نجرّد المفاتيح والقيم بنفس الطريقة —
# من غير الخطوة دي كان أغلب الجدول ميشتغلش أصلا.
_STEMMED = {}
for _k, _vals in EXPANSIONS.items():
    _key = stem(normalize(_k))
    _bucket = _STEMMED.setdefault(_key, [])
    for _v in _vals:
        _sv = stem(normalize(_v))
        if _sv and _sv not in _bucket:
            _bucket.append(_sv)


def expand(tokens):
    """يرجّع التوكنز الأصلية + المرادفات القانونية بدون تكرار."""
    out = list(tokens)
    seen = set(tokens)
    for t in tokens:
        for extra in _STEMMED.get(t, ()):
            if extra not in seen:
                seen.add(extra)
                out.append(extra)
    return out
